export interface LogoProps {
  /** Высота знака в px; слово и зазор масштабируются пропорционально. */
  size?: number;
  /** Только знак, без слова. */
  markOnly?: boolean;
  /** Цвет слова. Знак всегда лаймовый. */
  wordColor?: string;
  className?: string;
}

/**
 * Связка «знак + слово». Цвета — как в сайдбаре: знак лаймом, слово основным
 * текстом. Нужен другой цвет — берите части по отдельности.
 */
export function Logo({
  size = LOGO_MARK_SIZE,
  markOnly = false,
  wordColor = 'var(--color-display)',
  className,
}: LogoProps) {
  return (
    <span
      className={className}
      style={{ display: 'inline-flex', alignItems: 'center', gap: size * GAP_TO_MARK }}
    >
      <LogoMark size={size} style={{ color: 'var(--color-brand)' }} />
      {!markOnly && (
        <LogoWordmark size={size * WORDMARK_TO_MARK} style={{ color: wordColor }} />
      )}
    </span>
  );
}
