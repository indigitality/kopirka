/**
 * Единые параметры движения. Значения продублированы из токенов
 * (--ease-out, --dur-fast/base), потому что motion принимает числа, а не CSS-переменные.
 *
 * Ниже — константы редизайна (Paper, R13 · «Стекло и движение»). Старые
 * экспорты оставлены как есть: на них держится всё, что ещё не мигрировано.
 */
export const EASE_OUT = [0.22, 1, 0.36, 1] as const;

export const DUR_FAST = 0.12;
export const DUR_BASE = 0.2;
export const DUR_SLOW = 0.32;

/** Появление поповера/меню: короткий подъём с лёгким масштабом. */
export const popTransition = { duration: DUR_BASE, ease: EASE_OUT } as const;

/* ── Редизайн ─────────────────────────────────────────────────────────────
   «Плавающие панели, поповеры, тосты появляются из blur 8 → 0, opacity 0 → 1,
   сдвиг 8 px к месту; пружина: жёсткость 380, демпфирование 32. Уход — те же
   значения назад, вдвое быстрее.» — узел «Панель · Движение», артборд R13.
*/

/** Пружина плавающих слоёв: панели, поповеры, тосты, модалки, нажатие кнопки. */
export const SPRING_PANEL = { type: 'spring', stiffness: 380, damping: 32 } as const;

/**
 * Та же пружина «вдвое быстрее» — для ухода.
 *
 * Форма движения сохраняется, а не просто режется длительность: частота
 * пружины ω ∝ √k, поэтому удвоение скорости — это k × 4; чтобы затухание
 * ζ = c / (2√(km)) осталось прежним, демпфирование идёт × 2.
 */
export const SPRING_PANEL_EXIT = { type: 'spring', stiffness: 1520, damping: 64 } as const;

